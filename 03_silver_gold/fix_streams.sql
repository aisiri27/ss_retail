    UNIT_RETAIL_PRICE::FLOAT            AS UNIT_RETAIL_PRICE,
    UNIT_LAUNCH_PRICE::FLOAT            AS UNIT_LAUNCH_PRICE,
    CURRENT_MSRP::FLOAT                 AS CURRENT_MSRP,

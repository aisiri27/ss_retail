SELECT COUNT(*) AS SILVER_PRODUCT_COUNT FROM DB_TEAM1.SILVER.PRODUCT;

CREATE OR REPLACE TABLE DB_TEAM1.SILVER.STORE AS
SELECT
    CHANNEL_DESC, CHANNEL_ID,

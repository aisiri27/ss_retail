    TRY_TO_DATE(COMP_DATE::STRING)          AS COMP_DATE,
    COMP_STATUS, PERIMETER,
    TRY_TO_TIMESTAMP(REPLACE(CREATED_TIMESTAMP, '-', ' '), 'YYYY MM DD HH24.MI.SS.FF6') AS CREATED_TIMESTAMP,
